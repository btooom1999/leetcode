fn closest_to_target(arr: Vec<i32>, target: i32) -> i32 {
    let mut prev = vec![];
    let mut res = i32::MAX;
    for num in arr {
        let mut cur = vec![];
        cur.push(num);
        for prev_num in prev {
            let next_num = num & prev_num;
            if cur.last().copied() != Some(next_num) {
                cur.push(next_num);
            }
        }

        for &num in &cur {
            res = res.min((num - target).abs());
        }

        if res == 0 {
            return res;
        }

        prev = cur;
    }

    res
}

